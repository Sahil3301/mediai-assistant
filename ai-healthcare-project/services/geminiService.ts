// Helper functions to generate mock responses
function generateMockDoctorAnalysis(patientNotes: string): string {
  if (!patientNotes || patientNotes.trim() === '') {
    return 'Insufficient data provided for analysis. Please provide more detailed patient information.';
  }
  
  return `
Medical Analysis Report

Patient Presentation:
${patientNotes.substring(0, 100)}${patientNotes.length > 100 ? '...' : ''}

Findings:
- Based on the provided information, the patient appears to present with symptoms consistent with [condition].
- Key indicators include [symptoms extracted from notes].
- Differential diagnoses to consider: [potential conditions].

Recommendations:
- Recommend further diagnostic testing including [tests].
- Consider consultation with [specialist] for comprehensive evaluation.
- Monitor for changes in [specific symptoms].

Additional Notes:
- Patient history suggests potential risk factors for [condition].
- Current presentation may be complicated by [factors].

This analysis is generated by AI and should be verified by a qualified healthcare professional before making clinical decisions.
`;
}

function generateMockLaymanSummary(patientNotes: string): string {
  if (!patientNotes || patientNotes.trim() === '') {
    return 'Not enough information was provided to create a summary. Please provide more details about your condition.';
  }
  
  return `
In simple terms, your symptoms might be related to a condition affecting your [body system]. 

What this means:
- Your symptoms like [simplified symptoms] are common with this type of condition
- This is typically caused by [simplified cause]
- Many people experience similar symptoms

Next steps that your doctor might recommend:
- Some tests to confirm what's happening
- Possibly some medication to help with your symptoms
- Follow-up visits to track your progress

Remember, this is just a computer-generated summary to help you understand medical terms. Your doctor will provide you with accurate information specific to your situation.
`;
}
