import time
from typing import TypedDict, Optional
import asyncio # Added asyncio import

class AnalysisResult(TypedDict):
    doctorAnalysis: str
    laymanSummary: str

def _generate_mock_doctor_analysis(patient_notes: str) -> str:
    if not patient_notes or patient_notes.strip() == '':
        return 'Insufficient data provided for analysis. Please provide more detailed patient information.'

    return f'''
Medical Analysis Report (Mock Data)

Patient Presentation:
{patient_notes[:100]}{'...' if len(patient_notes) > 100 else ''}

Findings:
- Based on the provided information, the patient appears to present with symptoms consistent with [mock condition based on notes: e.g., common cold if notes mention cough/sore throat].
- Key indicators include [mock symptoms extracted or inferred from notes].
- Differential diagnoses to consider: [mock potential conditions].

Recommendations:
- Recommend further diagnostic testing including [mock tests].
- Consider consultation with [mock specialist] for comprehensive evaluation.
- Monitor for changes in [specific mock symptoms].

Additional Notes:
- Patient history suggests potential risk factors for [mock condition].
- Current presentation may be complicated by [mock factors].

This analysis is generated by AI and should be verified by a qualified healthcare professional before making clinical decisions.
'''

def _generate_mock_layman_summary(patient_notes: str) -> str:
    if not patient_notes or patient_notes.strip() == '':
        return 'Not enough information was provided to create a summary. Please provide more details about your condition.'

    return f'''
In simple terms (Mock Data), your symptoms might be related to a condition affecting your [mock body system].

What this means:
- Your symptoms like [simplified mock symptoms] are common with this type of condition.
- This is typically caused by [simplified mock cause].
- Many people experience similar symptoms.

Next steps that your doctor might recommend:
- Some tests to confirm what's happening.
- Possibly some medication to help with your symptoms.
- Follow-up visits to track your progress.

Remember, this is just a computer-generated summary to help you understand medical terms. Your doctor will provide you with accurate information specific to your situation.
'''

async def analyze_medical_data(
    patient_notes: str,
    image_base64: Optional[str] = None,
    image_mime_type: Optional[str] = None,
    use_search_grounding: bool = False
) -> AnalysisResult:
    """
    Analyzes medical data. Currently returns mock data.
    Simulates an API call with a delay.
    """
    print(f"analyze_medical_data called with patient_notes: '{patient_notes[:50]}...', use_search_grounding: {use_search_grounding}")
    # In a real implementation, image_base64 and image_mime_type would be used.
    # And use_search_grounding would be passed to the actual API.

    try:
        # Simulate API delay
        await asyncio.sleep(2.5) # Using asyncio.sleep for async function

        # For demo purposes, return mock data
        doctor_analysis = _generate_mock_doctor_analysis(patient_notes)
        layman_summary = _generate_mock_layman_summary(patient_notes)

        return AnalysisResult(doctorAnalysis=doctor_analysis, laymanSummary=layman_summary)

    except Exception as e:
        print(f"Error in analyze_medical_data: {e}")
        return AnalysisResult(
            doctorAnalysis=f"Error: Failed to generate analysis. {e}",
            laymanSummary=f"Error: Failed to generate summary. {e}"
        )

